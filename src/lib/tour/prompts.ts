/**
 * 「提示词」页新手教程。
 *
 * ══ 主线思路 ══════════════════════════════════════════════════════════
 * 这一页干的只有一件事：**维护要注入给 AI 的正文文本**（一个 .md 一个文件，
 * 就躺在 _assets/prompts 里）。所以步骤按用户真实的干活顺序走：
 *
 *   认清这一页的定位 → 看懂左边列表和搜索 → 把缺的文件补进来（文件/文件夹）
 *   → 挑一份打开 → 在编辑器改 → 保存落盘 → 用预览确认没选错 → 不想要就删
 *   → 最后回到「目标」页看它怎么被引用。
 *
 * 不按界面从左到右讲，因为那样会把「改完要保存」这件最要命的事拆散 ——
 * 用户记住的是「备料 → 改 → 保存 → 装」，不是一堆按钮的位置。
 *
 * ══ 为什么需要 before ════════════════════════════════════════════════
 * 右栏的「EDITOR / 正文」和「PREVIEW / 正文首行」是**条件渲染**的：没选中
 * 文件时那里只有一张「选择左侧文件」的空状态，两处锚点都不存在，那几步会
 * 退化成居中卡片（能读，但没了高亮很干）。所以下面用 ensureFileSelected()
 * 先把左侧第一行点开。
 *
 * ══ 只加锚点、不改逻辑的那一边 ══════════════════════════════════════
 * 本文件的锚点全部来自 pages/prompts.tsx 上真实存在的 data-tour 属性。
 * 其中「删除」没有独立锚点（垃圾桶在每行内部），挂在文件行上高亮整行 ——
 * 垃圾桶本来就在这个框里，指得不算错。
 */

/**
 * 保证右栏「EDITOR / 正文」在场。
 *
 * 右栏没选中文件时只有空状态，编辑器 / 预览 / 保存三处锚点全都不存在。
 * 这里先把左侧第一个文件行点开，让后续步骤有东西可指。
 *
 * 已经选中过文件时（进页面时会自动打开第一个）直接返回：既不做无谓的
 * 重复点击，也避免在用户有未保存改动时触发「放弃修改？」确认框。
 */
function ensureFileSelected(): void {
  if (anchorOf('prompts.editor')) return
  clickAnchor('prompts.file-first')
}

